#!/usr/bin/env node
/**
 * Importa una COPIA de la base SQLite a un esquema Postgres de staging.
 *
 * Garantías:
 *   - La ruta de origen nunca se abre con SQLite: se copia primero a un
 *     directorio temporal y se verifica su sha256 antes/después.
 *   - Solo escribe en la base/schema indicados. Exige --replace para borrar un
 *     schema existente.
 *   - Conserva todas las tablas y columnas; los tipos se mapean de forma
 *     conservadora (INTEGER→bigint, REAL→double precision, resto→text).
 *   - Verifica conteos por tabla y el digest de settings.
 *
 * Uso:
 *   node services/db/import-sqlite-to-postgres.mjs \
 *     --source /tmp/copy-v31.sqlite --database qvaapply_f1 --replace
 *
 * Conexión: usa `psql` y sus variables habituales (PGHOST, PGPORT, PGUSER,
 * PGPASSWORD, PGDATABASE). No hay credenciales en este script.
 */
import { createHash } from "node:crypto";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { DatabaseSync } from "node:sqlite";

const args = parseArgs(process.argv.slice(2));
const source = resolve(args.source);
const database = args.database;
const schema = args.schema;
const staging = mkdtempSync(join(tmpdir(), "qva-sqlite-pg-"));
const copy = join(staging, basename(source));

const sourceShaBefore = sha256File(source);
copyFileSync(source, copy);

let sqlite;
try {
  sqlite = new DatabaseSync(copy, { readOnly: true });
  const tables = sqlite
    .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
    .all()
    .map((row) => String(row.name));
  const schemaVersion = Number(
    sqlite.prepare("SELECT MAX(version) AS v FROM schema_migrations").get()?.v ?? 0,
  );

  if (args.replace) {
    psql(["-c", `DROP SCHEMA IF EXISTS ${q(schema)} CASCADE`]);
  } else if (schemaExists()) {
    throw new Error(`El schema ${schema} ya existe; usa --replace para recrearlo.`);
  }

  const create = [`CREATE SCHEMA ${q(schema)}`];
  const definitions = new Map();
  const identities = [];
  for (const table of tables) {
    const columns = sqlite.prepare(`PRAGMA table_info(${q(table)})`).all();
    definitions.set(table, columns);
    const tableSql = String(
      sqlite.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name=?").get(table)?.sql ?? "",
    );
    const autoincrement = /AUTOINCREMENT/i.test(tableSql);
    const primaryColumns = columns
      .filter((column) => Number(column.pk) > 0)
      .sort((left, right) => Number(left.pk) - Number(right.pk));
    const parts = columns.map((column) => {
      let type = postgresType(column.type);
      if (autoincrement && primaryColumns.length === 1 && primaryColumns[0].name === column.name)
        type += " GENERATED BY DEFAULT AS IDENTITY";
      return `${q(column.name)} ${type}`;
    });
    const primary = primaryColumns.map((column) => q(column.name));
    if (primary.length) parts.push(`PRIMARY KEY (${primary.join(", ")})`);
    create.push(`CREATE TABLE ${q(schema)}.${q(table)} (${parts.join(", ")})`);
    if (autoincrement && primaryColumns.length === 1) {
      identities.push({ table, column: String(primaryColumns[0].name) });
    }
  }
  create.push(
    `CREATE TABLE ${q(schema)}._import_manifest (` +
      `source text NOT NULL, source_sha256 text NOT NULL, schema_version integer NOT NULL, ` +
      `tables integer NOT NULL, rows bigint NOT NULL, imported_at timestamptz NOT NULL DEFAULT now())`,
  );
  psql(["-c", create.join(";\n")]);

  let totalRows = 0;
  const counts = {};
  for (const table of tables) {
    const columns = definitions.get(table).map((column) => String(column.name));
    const rows = sqlite.prepare(`SELECT ${columns.map(q).join(", ")} FROM ${q(table)}`).all();
    const csv = encodeCsv(
      columns,
      rows.map((row) => columns.map((column) => row[column])),
    );
    psql(
      [
        "-c",
        `\\copy ${q(schema)}.${q(table)} FROM STDIN WITH (FORMAT csv, HEADER true)`,
      ],
      csv,
    );
    counts[table] = rows.length;
    totalRows += rows.length;
  }

  const sequenceStatements = identities.map(
    ({ table, column }) =>
      `SELECT setval(pg_get_serial_sequence('${schema}.${table}', '${column}'), ` +
      `COALESCE((SELECT MAX(${q(column)}) FROM ${q(schema)}.${q(table)}), 0) + 1, false)`,
  );
  if (sequenceStatements.length) psql(["-c", sequenceStatements.join(";\n")]);

  const indexStatements = [];
  for (const table of tables) {
    const indexes = sqlite.prepare(`PRAGMA index_list(${q(table)})`).all();
    for (const index of indexes) {
      if (String(index.origin) === "pk") continue;
      const info = sqlite
        .prepare(`PRAGMA index_info(${q(index.name)})`)
        .all()
        .sort((left, right) => Number(left.seq) - Number(right.seq));
      if (!info.length || info.some((column) => column.name === null || column.name === undefined)) continue;
      const columns = info.map((column) => q(column.name));
      const unique = Number(index.unique) === 1 ? "UNIQUE " : "";
      const name = `idx_${table}_${index.name}`.replace(/[^A-Za-z0-9_]/g, "_");
      indexStatements.push(
        `CREATE ${unique}INDEX ${q(name)} ON ${q(schema)}.${q(table)} (${columns.join(", ")})`,
      );
    }
  }
  if (indexStatements.length) psql(["-c", indexStatements.join(";\n")]);

  const foreignStatements = [];
  let foreignKeyCount = 0;
  for (const table of tables) {
    const foreignKeys = sqlite.prepare(`PRAGMA foreign_key_list(${q(table)})`).all();
    const groups = new Map();
    for (const foreignKey of foreignKeys) {
      const id = Number(foreignKey.id);
      if (!groups.has(id)) groups.set(id, []);
      groups.get(id).push(foreignKey);
    }
    for (const [id, group] of groups) {
      const columns = group.sort((a, b) => Number(a.seq) - Number(b.seq)).map((item) => q(item.from));
      const target = q(group[0].table);
      if (group.some((item) => item.to === null || item.to === undefined)) continue;
      const targetColumns = group.map((item) => q(item.to));
      const name = `fk_${table}_${id}`.replace(/[^A-Za-z0-9_]/g, "_");
      foreignStatements.push(
        `ALTER TABLE ${q(schema)}.${q(table)} ADD CONSTRAINT ${q(name)} ` +
          `FOREIGN KEY (${columns.join(", ")}) REFERENCES ${q(schema)}.${target} (${targetColumns.join(", ")})`,
      );
      foreignKeyCount += 1;
    }
  }
  if (foreignStatements.length) psql(["-c", foreignStatements.join(";\n")]);

  const settingsExpected = settingsDigest();
  const settingsActual = psql([
    "-At",
    "-c",
    `SELECT md5(string_agg(key || chr(31) || value, E'\\n' ORDER BY key COLLATE "C")) FROM ${q(schema)}.settings`,
  ]).trim();
  if (settingsExpected !== settingsActual) {
    throw new Error(`digest de settings distinto: ${settingsExpected} != ${settingsActual}`);
  }

  const mismatches = [];
  for (const table of tables) {
    const actual = Number(
      psql(["-At", "-c", `SELECT count(*) FROM ${q(schema)}.${q(table)}`]).trim(),
    );
    if (actual !== counts[table]) {
      mismatches.push({ table, sqlite: counts[table], postgres: actual });
    }
  }

  const manifest = {
    source: basename(source),
    sourceSha256: sourceShaBefore,
    sourceSchemaVersion: schemaVersion,
    schema,
    tables: tables.length,
    rows: totalRows,
    settingsDigest: settingsActual,
    indexes: indexStatements.length,
    foreignKeys: foreignKeyCount,
    identities: identities.length,
    counts,
    mismatches,
  };
  psql([
    "-c",
    `INSERT INTO ${q(schema)}._import_manifest (source, source_sha256, schema_version, tables, rows)
     VALUES ('${escapeLiteral(basename(source))}', '${sourceShaBefore}', ${schemaVersion}, ${tables.length}, ${totalRows})`,
  ]);

  const sourceShaAfter = sha256File(source);
  if (sourceShaBefore !== sourceShaAfter) {
    throw new Error("la base de origen cambió durante la importación");
  }
  if (mismatches.length) {
    throw new Error(`conteos distintos en ${mismatches.length} tabla(s)`);
  }

  if (args.manifest) writeFileSync(resolve(args.manifest), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(JSON.stringify(manifest, null, 2));
  if (sourceShaAfter !== sourceShaBefore) process.exitCode = 1;
} finally {
  sqlite?.close();
  rmSync(staging, { recursive: true, force: true });
}

function parseArgs(argv) {
  const result = {
    source: "data/qvaapply.sqlite",
    database: "qvaapply_f1",
    schema: "raw",
    replace: false,
    manifest: undefined,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--source") result.source = argv[++index];
    else if (arg === "--database") result.database = argv[++index];
    else if (arg === "--schema") result.schema = argv[++index];
    else if (arg === "--manifest") result.manifest = argv[++index];
    else if (arg === "--replace") result.replace = true;
    else throw new Error(`Argumento desconocido: ${arg}`);
  }
  return result;
}

function psql(argv, input) {
  const result = spawnSync(
    "psql",
    ["-X", "-q", "-v", "ON_ERROR_STOP=1", "-d", database, ...argv],
    { input, encoding: "utf8" },
  );
  if (result.status !== 0) {
    throw new Error(`psql falló: ${(result.stderr || result.stdout || "").trim()}`);
  }
  return result.stdout;
}

function schemaExists() {
  const output = psql([
    "-At",
    "-c",
    `SELECT count(*) FROM information_schema.schemata WHERE schema_name = '${escapeLiteral(schema)}'`,
  ]).trim();
  return Number(output) > 0;
}

function postgresType(type) {
  const value = String(type || "").toUpperCase();
  if (value.includes("INT")) return "bigint";
  if (value.includes("REAL") || value.includes("FLOA") || value.includes("DOUB")) return "double precision";
  if (value.includes("BLOB")) return "bytea";
  return "text";
}

function encodeCsv(columns, rows) {
  const lines = [columns.map(csvCell).join(",")];
  for (const row of rows) lines.push(row.map(csvCell).join(","));
  return `${lines.join("\n")}\n`;
}

function csvCell(value) {
  if (value === null || value === undefined) return "";
  let text;
  if (typeof value === "bigint") text = value.toString();
  else if (value instanceof Uint8Array) text = `\\x${Buffer.from(value).toString("hex")}`;
  else text = String(value);
  if (text === "" || /[",\r\n]/.test(text) || /^\s|\s$/.test(text)) {
    return `"${text.replaceAll('"', '""')}"`;
  }
  return text;
}

function settingsDigest() {
  const rows = sqlite.prepare("SELECT key, value FROM settings ORDER BY key").all();
  const hash = createHash("md5");
  hash.update(rows.map((row) => `${row.key}\x1f${row.value}`).join("\n"));
  return hash.digest("hex");
}

function sha256File(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

function q(identifier) {
  return `"${String(identifier).replaceAll('"', '""')}"`;
}

function escapeLiteral(value) {
  return String(value).replaceAll("'", "''");
}
